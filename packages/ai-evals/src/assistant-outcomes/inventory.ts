export type ActionCoverage =
  | { kind: "tools"; tools: readonly string[] }
  | { kind: "excluded"; reason: string };
export interface ActionInventoryEntry {
  id: string;
  screen: string;
  action: string;
  channels: readonly string[];
  coverage: ActionCoverage;
}

function actions(
  prefix: string,
  screen: string,
  tools: readonly string[],
  rows: readonly (readonly [string, string])[],
  channels: readonly string[] = [],
): ActionInventoryEntry[] {
  return rows.map(([id, action]) => ({
    id: `${prefix}.${id}`,
    screen,
    action,
    channels,
    coverage: { kind: "tools", tools },
  }));
}
function fields(
  prefix: string,
  screen: string,
  tool: string,
  names: readonly string[],
) {
  return actions(
    prefix,
    screen,
    [tool, "undo_change"],
    names.map((name) => [name, `Edit ${name}`] as const),
  );
}
const navigate = ["open_in_app"];
const control = ["control_app"];
const excluded = (
  id: string,
  action: string,
  reason: string,
): ActionInventoryEntry => ({
  id: `assistant.${id}`,
  screen: "Assistant",
  action,
  channels: [],
  coverage: { kind: "excluded", reason },
});

